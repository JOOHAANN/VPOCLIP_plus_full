def dump(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_suffix(path.suffix + ".tmp")
    temp.write_text(json.dumps(value, indent=2, allow_nan=False), encoding="utf-8")
    temp.replace(path)


def attach_object_tracks(raw: GPUCache, track_root: Path, split: str) -> None:
    path = track_root / split / "object_position_track.npy"
    if not path.exists():
        raise FileNotFoundError(
            f"missing object trajectory cache {path}; run "
            "rl.build_object_position_tracks first"
        )
    array = np.load(path, mmap_mode="r", allow_pickle=False)
    expected = (raw.num_episodes, NUM_VIEWS, NUM_FRAMES, NUM_OBJECT_CLASSES, 4)
    if tuple(array.shape) != expected:
        raise ValueError(f"object track shape {array.shape} != {expected}")
    raw.object_position_track = torch.from_numpy(np.array(array, copy=True)).to(
        device=raw.device, dtype=torch.float32, non_blocking=False
    )


def angle_candidate_features(candidate: torch.Tensor) -> torch.Tensor:
    """Encode directions only; the last validity field is not a feature."""

    camera_angle = candidate[..., :2]
    relative_delta = candidate[..., 2:4]
    current_angle = candidate[..., 4:6]
    camera_harmonic = torch.stack(
        (
            2 * camera_angle[..., 0] * camera_angle[..., 1],
            camera_angle[..., 1].square() - camera_angle[..., 0].square(),
        ),
        -1,
    )
    delta_harmonic = torch.stack(
        (
            2 * relative_delta[..., 0] * relative_delta[..., 1],
            relative_delta[..., 1].square() - relative_delta[..., 0].square(),
        ),
        -1,
    )
    return torch.cat(
        (camera_angle, relative_delta, current_angle, camera_harmonic, delta_harmonic), -1
    )


def person_trajectory_from_pose(pose: torch.Tensor) -> torch.Tensor:
    """Convert [B,V,442] cached pose into [B,V,T,4] center/velocity tracks."""

    points = pose.reshape(*pose.shape[:-1], NUM_FRAMES, 17, 2)
    torso_ids = torch.as_tensor([5, 6, 11, 12], device=pose.device)
    torso = points.index_select(-2, torso_ids)
    present = torso.norm(dim=-1) > 0.02
    denom = present.sum(-1, keepdim=True).clamp_min(1).to(points.dtype)
    center = (torso * present[..., None]).sum(-2) / denom
    center = torch.nan_to_num(center)
    velocity = torch.zeros_like(center)
    velocity[:, :, 1:, :] = center[:, :, 1:, :] - center[:, :, :-1, :]
    return torch.cat((center, velocity), -1)


def build_trajectory_state(
    raw: GPUCache,
    episodes: torch.Tensor,
    history: torch.Tensor,
    history_count: torch.Tensor,
) -> dict[str, torch.Tensor]:
    """Build a strictly causal geometry + person/object trajectory state."""

    episodes = episodes.long()
    history = history.long()
    count = history_count.long().clamp(1, history.shape[1])
    batch = episodes.shape[0]
    positions = torch.arange(history.shape[1], device=episodes.device)[None, :]
    observed = positions < count[:, None]
    observed_f = observed.float()
    denominator = count.float().clamp_min(1.0)[:, None]
    current = history.gather(1, (count - 1)[:, None]).squeeze(1)

    observed_pose = raw.pose[episodes[:, None], history]
    person = person_trajectory_from_pose(observed_pose)
    person = (person * observed_f[:, :, None, None]).sum(1) / denominator[:, :, None]

    object_track = raw.object_position_track[episodes[:, None], history]
    # [B,H,T,O,4] -> [B,H,T,O,6]: presence, absolute xy, confidence and
    # position relative to the detected person center.
    person_xy = person_trajectory_from_pose(observed_pose)[..., :2]
    object_xy = object_track[..., 1:3]
    relative_xy = object_xy - person_xy[..., None, :]
    object_sensor = torch.cat((object_track, relative_xy), -1)
    object_sensor = (
        object_sensor * observed_f[:, :, None, None, None]
    ).sum(1) / denominator[:, :, None, None]

    observed_views = torch.zeros(
        (batch, NUM_VIEWS), dtype=torch.bool, device=episodes.device
    )
    observed_views.scatter_(1, history, observed)
    current_relative_angle = raw.geometry[episodes, current, :2]
    geometry = raw.geometry[episodes, :, :2]
    sin_delta = (
        geometry[..., 0] * current_relative_angle[:, None, 1]
        - geometry[..., 1] * current_relative_angle[:, None, 0]
    )
    cos_delta = (geometry * current_relative_angle[:, None]).sum(-1)
    valid = (
        raw.valid[episodes]
        & raw.reachable[episodes, current]
        & (~observed_views)
    )
    candidate = torch.cat(
        (
            geometry,
            torch.stack((sin_delta, cos_delta), -1),
            current_relative_angle[:, None].expand(-1, NUM_VIEWS, -1),
            valid[..., None].float(),
        ),
        -1,
    )
    return {
        "person_trajectory": person,
        "object_trajectory": object_sensor,
        "current_relative_angle": current_relative_angle,
        "candidate": candidate,
        "mask": valid,
    }


class AngleObjectTrajectoryPolicy(nn.Module):
    """Low-capacity factorized scorer over physical sensor trajectories."""

    def __init__(self) -> None:
        super().__init__()
        self.person_temporal = nn.Sequential(
            nn.Conv1d(4, 16, kernel_size=3, padding=1),
            nn.GroupNorm(4, 16),
            nn.GELU(),
        )
        self.person_summary = nn.Sequential(
            nn.Linear(16 * NUM_FRAMES, 32), nn.LayerNorm(32), nn.GELU()
        )
        self.object_temporal = nn.Sequential(
            nn.Conv1d(NUM_OBJECT_CLASSES * OBJECT_CHANNELS, 64, kernel_size=3, padding=1),
            nn.GroupNorm(8, 64),
            nn.GELU(),
        )
        self.object_summary = nn.Sequential(
            nn.Linear(64 * NUM_FRAMES, 64), nn.LayerNorm(64), nn.GELU()
        )
        self.angle = nn.Sequential(nn.Linear(2, 16), nn.LayerNorm(16), nn.GELU())
        self.context = nn.Sequential(
            nn.Linear(32 + 64 + 16, 64), nn.LayerNorm(64), nn.GELU()
        )
        self.candidate = nn.Sequential(
            nn.Linear(10, 64), nn.LayerNorm(64), nn.GELU()
        )
        self.context_to_action = nn.Linear(64, 64, bias=False)
        self.residual = nn.Sequential(
            nn.Linear(128, 32), nn.GELU(), nn.Linear(32, 1)
        )

    def forward(self, state: dict[str, torch.Tensor]) -> torch.Tensor:
        person = state["person_trajectory"]
        person = self.person_temporal(person.transpose(1, 2)).flatten(1)
        person = self.person_summary(person)
        obj = state["object_trajectory"]
        obj = obj.reshape(obj.shape[0], NUM_FRAMES, NUM_OBJECT_CLASSES * OBJECT_CHANNELS)
        obj = self.object_temporal(obj.transpose(1, 2)).flatten(1)
        obj = self.object_summary(obj)
        angle = self.angle(state["current_relative_angle"])
        context = self.context(torch.cat((person, obj, angle), -1))
        candidate = self.candidate(angle_candidate_features(state["candidate"]))
        expanded = context[:, None].expand(-1, NUM_VIEWS, -1)
        q = (self.context_to_action(context)[:, None] * candidate).sum(-1) / math.sqrt(64.0)
        q = q + 0.20 * self.residual(torch.cat((expanded, candidate), -1)).squeeze(-1)
        return q


@torch.inference_mode()
def policy_rollout_trajectory(
    model: nn.Module,
    raw: GPUCache,
    episodes: torch.Tensor,
    starts: torch.Tensor,
) -> dict[str, torch.Tensor]:
    model.eval()
    batch = episodes.shape[0]
    one = torch.ones(batch, dtype=torch.long, device=episodes.device)
    state1 = build_trajectory_state(raw, episodes, starts[:, None], one)
    keep1 = state1["mask"].any(-1)
    episodes, starts = episodes[keep1], starts[keep1]
    state1 = {key: value[keep1] for key, value in state1.items()}
    action1 = model(state1).masked_fill(~state1["mask"], -torch.inf).argmax(-1)

    history2 = torch.stack((starts, action1), 1)
    two = torch.full((len(episodes),), 2, dtype=torch.long, device=episodes.device)
    state2 = build_trajectory_state(raw, episodes, history2, two)
    keep2 = state2["mask"].any(-1)
    episodes, starts, action1 = episodes[keep2], starts[keep2], action1[keep2]
    history2 = history2[keep2]
    state2 = {key: value[keep2] for key, value in state2.items()}
    action2 = model(state2).masked_fill(~state2["mask"], -torch.inf).argmax(-1)

    history3 = torch.stack((history2[:, 0], history2[:, 1], action2), 1)
    three = torch.full((len(episodes),), 3, dtype=torch.long, device=episodes.device)
    state3 = build_trajectory_state(raw, episodes, history3, three)
    q3 = model(state3)
    mask3 = state3["mask"]
    future_present = mask3.any(-1)
    future_action = q3.masked_fill(~mask3, -torch.inf).argmax(-1)
    future_q = q3.gather(1, future_action[:, None]).squeeze(1)
    return {
        "episodes": episodes,
        "starts": starts,
        "action1": action1,
        "action2": action2,
        "future_action": future_action,
        "future_present": future_present,
        "future_q": future_q,
        "mask3": mask3,
    }


def evaluate_protocol(
    model: nn.Module,
    raw: GPUCache,
    classes: Sequence[int],
    protocol: str,
    seed: int,
) -> dict[str, Any]:
    bank = class_bank_tensor(classes, raw.device)
    eligible = torch.isin(raw.labels, bank) & (raw.valid.sum(-1) >= 3)
    episodes = eligible.nonzero().flatten()
    if protocol.startswith("fixed"):
        start = int(protocol.removeprefix("fixed"))
        episodes = (eligible & raw.valid[:, start]).nonzero().flatten()
        starts = torch.full_like(episodes, start)
    elif protocol == "random_start":
        starts = choose_random_starts(raw, episodes, seed)
    else:
        raise ValueError(protocol)
    single = {"top1": 0.0} if not len(episodes) else _single_metrics(raw, episodes, starts, bank)
    rollout = policy_rollout_trajectory(model, raw, episodes, starts)
    policy_episodes = rollout["episodes"]
    policy_paths = torch.stack(
        (rollout["starts"], rollout["action1"], rollout["action2"]), 1
    )
    policy = (
        metrics_for_paths(raw, policy_episodes, policy_paths, bank)
        if len(policy_episodes)
        else {"top1": 0.0, "mean_entropy": 0.0, "mean_movement_cost": 0.0, "episodes": 0.0}
    )
    random_exact, _ = random_exact_metrics(raw, episodes, starts, bank)
    random_ep, random_paths, _ = sample_random_paths(raw, episodes, starts, seed + 17)
    random_sample = (
        metrics_for_paths(raw, random_ep, random_paths, bank)
        if len(random_ep)
        else {"top1": 0.0, "mean_entropy": 0.0, "mean_movement_cost": 0.0, "episodes": 0.0}
    )
    oracle_ep, oracle_path = oracle_paths(raw, episodes, starts, bank)
    oracle = (
        metrics_for_paths(raw, oracle_ep, oracle_path, bank)
        if len(oracle_ep)
        else {"top1": 0.0, "mean_entropy": 0.0, "mean_movement_cost": 0.0, "episodes": 0.0}
    )
    all_weights = raw.valid[episodes].float().unsqueeze(-1)
    all_scores = (raw.logits[episodes] * all_weights).sum(1) / all_weights.sum(1).clamp_min(1.0)
    all_scores = all_scores.index_select(-1, bank)
    all_local = torch.searchsorted(bank, raw.labels[episodes])
    all_top1 = all_scores.argmax(-1).eq(all_local)
    future_legal = rollout["mask3"].gather(1, rollout["future_action"][:, None]).squeeze(1)
    return {
        "protocol": protocol,
        "class_bank": [int(x) for x in classes],
        "episodes_before_two_move_filter": int(len(episodes)),
        "episodes_policy_completed": int(len(policy_episodes)),
        "completion_rate": float(len(policy_episodes) / max(len(episodes), 1)),
        "metrics": {
            "single_start": single,
            "random_3view_sampled": random_sample,
            "random_3view_exact": random_exact,
            "policy_3view": policy,
            "oracle_3view": oracle,
            "all_valid_views": {"top1": float(all_top1.float().mean()) if len(episodes) else 0.0},
        },
        "future_fourth_prediction": {
            "episodes_after_three_observed": int(len(policy_episodes)),
            "remaining_view_present_rate": float(rollout["future_present"].float().mean()) if len(policy_episodes) else 0.0,
            "predicted_action_legal_rate": float(future_legal.float().mean()) if len(policy_episodes) else 0.0,
            "mean_predicted_q": float(rollout["future_q"].mean()) if len(policy_episodes) else 0.0,
        },
    }


def train_seed(
    seed: int,
    train_raw: GPUCache,
    val_raw: GPUCache,
    device: torch.device,
    args: argparse.Namespace,
    output_root: Path,
) -> dict[str, Any]:
    run = output_root / f"seed_{seed}"
    run.mkdir(parents=True, exist_ok=True)
    complete = run / "complete.json"
    if complete.exists():
        return json.loads(complete.read_text(encoding="utf-8"))
    torch.manual_seed(seed)
    np.random.seed(seed)
    torch.cuda.manual_seed_all(seed)
    generator = torch.Generator(device=device).manual_seed(seed)
    model = AngleObjectTrajectoryPolicy().to(device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.learning_rate, weight_decay=0.04)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, args.epochs, eta_min=args.learning_rate * 0.05)
    bank = class_bank_tensor(SEEN_CLASSES, device)
    eligible = (train_raw.valid.sum(-1) == 4) & torch.isin(train_raw.labels, bank)
    pool = eligible.nonzero().flatten()
    if not len(pool):
        raise RuntimeError("no complete four-view seen training episodes")
    audit = {
        "seed": seed,
        "training_episodes_four_view_seen": int(len(pool)),
        "training_classes": SEEN_CLASSES,
        "pseudo_unseen_for_selection": PSEUDO_UNSEEN_CLASSES,
        "true_unseen_test_only": TRUE_UNSEEN_CLASSES,
        "policy_inputs_only": [
            "sample-specific human/camera relative angle",
            "causal 13-frame person center/velocity trajectory",
            "causal 13-frame per-class object presence/position/confidence trajectory",
            "object position relative to person center",
        ],
        "policy_inputs_excluded": [
            "RGB/video embedding", "VPOCLIP z", "skeleton embedding",
            "semantic belief", "current logits", "class ID", "future-view features",
        ],
        "training_target": "offline seen-bank delta margin; VPOCLIP logits only construct target",
        "trajectory": "one observed -> second; two observed -> third; three observed -> fourth prediction only",
        "final_fusion": "mean logits of exactly three observed views",
        "movement_cost_in_reward": False,
        "object_track_source": "YOLO custom50 on the same 13 frame indices as the VPOCLIP cache",
        "frame_shape": [640, 480],
    }
    dump(run / "audit.json", audit)
    best_score = -float("inf")
    best_epoch = 0
    for epoch in range(1, args.epochs + 1):
        model.train()
        begun = time.monotonic()
        losses: list[float] = []
        for _ in range(args.updates_per_epoch):
            ids = torch.randint(len(pool), (args.batch_size,), device=device, generator=generator)
            episodes = pool[ids]
            permutation = torch.rand((args.batch_size, NUM_VIEWS), device=device, generator=generator).argsort(-1)
            stage = torch.multinomial(
                torch.as_tensor([0.45, 0.45, 0.10], device=device), args.batch_size,
                replacement=True, generator=generator,
            ) + 1
            history = permutation[:, :3]
            state = build_trajectory_state(train_raw, episodes, history, stage)
            utility = utility_targets(train_raw, episodes, history, stage, state["mask"], bank)
            state, utility = permute_candidates(state, utility, generator)
            prediction = model(state)
            loss, _ = multistep_loss(prediction, utility, state["mask"], stage)
            if not torch.isfinite(loss):
                raise FloatingPointError(f"non-finite loss seed={seed}, epoch={epoch}")
            optimizer.zero_grad(set_to_none=True)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 5.0)
            optimizer.step()
            losses.append(float(loss.detach()))
        scheduler.step()
        torch.cuda.synchronize(device)
        validation = evaluate_protocol(model, val_raw, PSEUDO_UNSEEN_CLASSES, "fixed0", seed + 90117)
        metrics = validation["metrics"]
        score = float(metrics["policy_3view"]["top1"] - metrics["random_3view_exact"]["top1"])
        if score > best_score:
            best_score, best_epoch = score, epoch
        payload = {
            "online": model.state_dict(), "optimizer": optimizer.state_dict(),
            "scheduler": scheduler.state_dict(), "epoch": epoch, "best_score": best_score,
            "best_epoch": best_epoch, "seed": seed,
        }
        torch.save(payload, run / "last.pt")
        if score >= best_score:
            torch.save(payload, run / "best.pt")
        row = {
            "epoch": epoch, "seed": seed, "loss": float(np.mean(losses)),
            "seconds": time.monotonic() - begun,
            "samples_per_second": float(args.batch_size * args.updates_per_epoch / max(time.monotonic() - begun, 1e-6)),
            "validation_selection_score": score, "best_score": best_score, "best_epoch": best_epoch,
            "validation": metrics,
        }
        with (run / "train.log").open("a", encoding="utf-8", buffering=1) as log:
            log.write(json.dumps(row) + "\n")
        print(json.dumps({k: row[k] for k in ("epoch", "loss", "seconds", "validation_selection_score", "best_score", "best_epoch")}), flush=True)
    result = {
        "seed": seed, "best_score": best_score, "best_epoch": best_epoch,
        "checkpoint": str(run / "best.pt"), "output": str(run),
        "training_episodes": int(len(pool)),
    }
    dump(complete, result)
    return result


def final_evaluation(
    summaries: list[dict[str, Any]],
    val_raw: GPUCache,
    seen_raw: GPUCache,
    test_raw: GPUCache,
    device: torch.device,
    output_root: Path,
) -> None:
    chosen = max(summaries, key=lambda item: float(item["best_score"]))
    model = AngleObjectTrajectoryPolicy().to(device)
    saved = torch.load(Path(chosen["checkpoint"]), map_location=device, weights_only=False)
    model.load_state_dict(saved["online"], strict=True)
    model.eval()
    selection = {"criterion": "pseudo-unseen fixed0 policy gain", "chosen": chosen, "runs": summaries}
    dump(output_root / "selection.json", selection)
    reports: dict[str, Any] = {}
    for split_name, raw, classes in (
        ("val_pseudo_unseen", val_raw, PSEUDO_UNSEEN_CLASSES),
        ("seen_test", seen_raw, SEEN_CLASSES),
        ("true_unseen_5way", test_raw, TRUE_UNSEEN_CLASSES),
    ):
        reports[split_name] = {}
        for protocol in ("fixed0", "fixed1", "fixed2", "fixed3", "random_start"):
            report = evaluate_protocol(model, raw, classes, protocol, 20260910 + len(protocol))
            report["selected_seed"] = int(chosen["seed"])
            reports[split_name][protocol] = report
            dump(output_root / split_name / f"evaluation_{protocol}.json", report)
            print("ANGLE_OBJECT_TRAJECTORY_EVALUATION", split_name, protocol, json.dumps(report["metrics"]), flush=True)
    dump(output_root / "summary.json", {
        "variant": "multistep_angle_object_trajectory_policy_v1",
        "base_comparison": "multistep_angle_object_policy_v1",
        "selection": selection,
        "policy_inputs": [
            "sample-specific human/camera relative angle",
            "causal 13-frame person center/velocity trajectory",
            "causal 13-frame per-class object presence/position/confidence trajectory",
            "object position relative to person center",
        ],
        "policy_inputs_excluded": ["RGB/video embedding", "VPOCLIP z", "skeleton embedding", "semantic belief", "current logits", "class ID", "future-view features"],
        "object_track_shape_per_episode": [NUM_VIEWS, NUM_FRAMES, NUM_OBJECT_CLASSES, 4],
        "reports": reports,
    })


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--cache-root", type=Path, default=CACHE_ROOT)
    parser.add_argument("--track-root", type=Path, default=TRACK_ROOT)
    parser.add_argument("--output-root", type=Path, default=OUTPUT_ROOT)
    parser.add_argument("--epochs", type=int, default=40)
    parser.add_argument("--batch-size", type=int, default=16384)
    parser.add_argument("--updates-per-epoch", type=int, default=64)
    parser.add_argument("--learning-rate", type=float, default=1e-4)
    parser.add_argument("--seeds", type=int, nargs="+", default=[20260909, 20260910, 20260911])
    parser.add_argument(
        "--unseen-classes", type=int, nargs="+", default=None,
        help="Override the class split for an isolated cache/recognizer run.",
    )
    parser.add_argument(
        "--pseudo-unseen-classes", type=int, nargs="+", default=None,
        help="Held-out seen classes used only for validation/model selection.",
    )
    args = parser.parse_args()
    if args.unseen_classes is not None:
        unseen = sorted(set(int(x) for x in args.unseen_classes))
        if not unseen or any(x < 0 or x >= NUM_CLASSES for x in unseen):
            raise ValueError(f"invalid unseen class IDs: {unseen}")
        seen = sorted(set(range(NUM_CLASSES)) - set(unseen))
        if args.pseudo_unseen_classes is None:
            raise ValueError("--pseudo-unseen-classes is required with --unseen-classes")
        pseudo = sorted(set(int(x) for x in args.pseudo_unseen_classes))
        if not pseudo or not set(pseudo).issubset(set(seen)):
            raise ValueError(
                f"pseudo-unseen classes must be a non-empty subset of seen classes; "
                f"seen={seen}, pseudo={pseudo}"
            )
        global SEEN_CLASSES, PSEUDO_UNSEEN_CLASSES, TRUE_UNSEEN_CLASSES
        SEEN_CLASSES = seen
        PSEUDO_UNSEEN_CLASSES = pseudo
        TRUE_UNSEEN_CLASSES = unseen
    if not torch.cuda.is_available():
        raise RuntimeError("CUDA is required")
    device = torch.device("cuda:0")
    torch.set_float32_matmul_precision("high")
    torch.backends.cuda.matmul.allow_tf32 = True
    torch.backends.cudnn.allow_tf32 = True
    args.output_root.mkdir(parents=True, exist_ok=True)
    dump(args.output_root / "config_resolved.json", {
        "cache_root": str(args.cache_root), "track_root": str(args.track_root),
        "output_root": str(args.output_root), "epochs": args.epochs,
        "batch_size": args.batch_size, "updates_per_epoch": args.updates_per_epoch,
        "learning_rate": args.learning_rate, "seeds": args.seeds,
        "seen_classes": SEEN_CLASSES,
        "pseudo_unseen_classes": PSEUDO_UNSEEN_CLASSES,
        "unseen_classes": TRUE_UNSEEN_CLASSES,
    })
    raw: dict[str, GPUCache] = {}
    for split in ("dqn_train", "val", "seen_test", "test"):
        raw[split] = GPUCache(args.cache_root / split, device)
        attach_view_valid(raw[split], args.cache_root, split)
        attach_object_tracks(raw[split], args.track_root, split)
    print("ANGLE_OBJECT_TRAJECTORY_CACHE_SHAPES", json.dumps({k: v.num_episodes for k, v in raw.items()}), flush=True)
    summaries = []
    for seed in args.seeds:
        summaries.append(train_seed(seed, raw["dqn_train"], raw["val"], device, args, args.output_root))
        torch.cuda.empty_cache()
    dump(args.output_root / "training_summary.json", summaries)
    final_evaluation(summaries, raw["val"], raw["seen_test"], raw["test"], device, args.output_root)
    print("ANGLE_OBJECT_TRAJECTORY_TRAIN_EVAL_COMPLETE", flush=True)


if __name__ == "__main__":
    main()
