"""Multi-step active-view policy using only geometric and temporal sensors.

This is a new isolated comparison.  The selector state contains no RGB/X3D
embedding, VPOCLIP z, skeleton embedding, semantic belief, current logits,
class ID, or future-view feature.  It contains only:

* the sample-specific human/camera relative angle and candidate geometry;
* the causal trajectory of the person in the current view, derived from the
  13 cached keypoint frames;
* the causal trajectory of detected objects, represented by per-class
  presence, image position and confidence at those same 13 frames.

The object trajectories are generated by ``build_object_position_tracks``;
the ordinary RL cache's single middle-frame object map is deliberately not
used as a trajectory.  At stage 1 the policy sees one view, at stage 2 it sees
the two observed views, and at stage 3 it predicts the fourth view only.  The
final HAR score fuses exactly the first three selected views.
"""

